"""Quality/latency metrics for a TaylorSeer run against its baseline run.

Both runs are described by the JSONL run logs `eval/bench.py` writes (see
`eval/benchlog.py`): the samples are paired by their global index in the data
file, the `base` images act as the reference and the `taylorseer` images as the
prediction. Usage:

    python eval/compute_metrics.py \
        --base_log outputs/logs/base.jsonl \
        --taylorseer_log outputs/logs/taylorseer_o2_i4_w3.jsonl \
        --data_path data/drawbench.jsonl
"""

import json
import statistics
import sys
import types
from dataclasses import dataclass, field
from pathlib import Path

import torch
from benchlog import RunLog, SampleRecord, load_run_log, load_samples
from PIL import Image
from torchmetrics.image import (
    LearnedPerceptualImagePatchSimilarity,
    PeakSignalNoiseRatio,
    StructuralSimilarityIndexMeasure,
)
from torchmetrics.image.fid import FrechetInceptionDistance
from torchmetrics.multimodal import CLIPScore
from torchvision.transforms import functional as tvf
from transformers.hf_argparser import HfArgumentParser


@dataclass
class MetricsArguments:
    """Arguments for computing metrics from the JSONL run logs of `eval/bench.py`.

    - base_log (str): Run log of the `base` run, used as the reference (target)
      images. Accepts a path, a glob pattern or a comma-separated list of both,
      e.g. "outputs/logs/base.chunk*.jsonl".
    - taylorseer_log (str): Run log of the `taylorseer` run, used as the
      predicted images. Same path syntax as `--base_log`.
    - data_path (str | None): Prompt data file the runs were launched with, used
      to recover each sample's prompt. Defaults to the `data_path` recorded in
      the run logs.
    - device (str): Device to run the metrics on.
    - batch_size (int): Batch size for the image-pair metrics.
    - report_path (str | None): Where to write the JSON report. Defaults to
      "<taylorseer log dir>/<taylorseer run name>.metrics.json".
    """

    base_log: str = field(default="outputs/logs/base.jsonl")
    taylorseer_log: str = field(default="outputs/logs/taylorseer.jsonl")
    data_path: str | None = field(default=None)
    device: str = field(default="cuda")
    batch_size: int = field(default=32)
    report_path: str | None = field(default=None)


@dataclass
class PairedSample:
    """One sample generated by both runs, with the prompt it was generated from."""

    index: int
    prompt: str
    seed: int
    base: SampleRecord
    taylorseer: SampleRecord


def to_tensor(images: list[Image.Image]) -> torch.Tensor:
    return torch.stack([tvf.to_tensor(image.convert("RGB")) for image in images])


def _pair_batches(
    pred: list[Image.Image],
    target: list[Image.Image],
    batch_size: int,
    device: str,
):
    """Yield `(pred, target)` tensor batches of shape ``[B, C, H, W]`` in ``[0, 1]``."""
    for i in range(0, len(pred), batch_size):
        yield (
            to_tensor(pred[i : i + batch_size]).to(device),
            to_tensor(target[i : i + batch_size]).to(device),
        )


@torch.inference_mode()
def calculate_psnr(
    pred: list[Image.Image],
    target: list[Image.Image],
    device: str = "cuda",
    batch_size: int = 32,
) -> float:
    metric = PeakSignalNoiseRatio(
        data_range=1.0,
        reduction="elementwise_mean",
    ).to(device)
    for pred_batch, target_batch in _pair_batches(pred, target, batch_size, device):
        metric.update(pred_batch, target_batch)
    score: torch.Tensor = metric.compute()
    return float(score.detach().cpu().item())


@torch.inference_mode()
def calculate_ssim(
    pred: list[Image.Image],
    target: list[Image.Image],
    device: str = "cuda",
    batch_size: int = 32,
) -> float:
    metric = StructuralSimilarityIndexMeasure(
        data_range=1.0,
        reduction="elementwise_mean",
    ).to(device)
    for pred_batch, target_batch in _pair_batches(pred, target, batch_size, device):
        metric.update(pred_batch, target_batch)
    score: torch.Tensor = metric.compute()
    return float(score.detach().cpu().item())


@torch.inference_mode()
def calculate_lpips(
    pred: list[Image.Image],
    target: list[Image.Image],
    device: str = "cuda",
    batch_size: int = 32,
) -> float:
    metric = LearnedPerceptualImagePatchSimilarity(
        net_type="alex",
        normalize=True,
    ).to(device)
    for pred_batch, target_batch in _pair_batches(pred, target, batch_size, device):
        metric.update(pred_batch, target_batch)
    score: torch.Tensor = metric.compute()
    return float(score.detach().cpu().item())


@torch.inference_mode()
def calculate_clip_score(
    pred: list[Image.Image],
    prompts: list[str],
    device: str = "cuda",
    batch_size: int = 32,
) -> float:
    metric = CLIPScore(model_name_or_path="openai/clip-vit-base-patch16").to(device)
    # CLIPScore's HF image processor always rescales by 1/255, so it expects
    # pixel values in [0, 255] rather than the [0, 1] range `to_tensor` gives.
    for i in range(0, len(pred), batch_size):
        images = (to_tensor(pred[i : i + batch_size]) * 255).to(device)
        metric.update(images, prompts[i : i + batch_size])
    score: torch.Tensor = metric.compute()
    return float(score.detach().cpu().item())


def _patch_for_image_reward() -> None:
    # `image-reward`'s vendored BLIP model imports these from
    # `transformers.modeling_utils`; newer `transformers` moved the first two to
    # `pytorch_utils` and dropped the third. Its `clip` dependency also does
    # `from pkg_resources import packaging`, which setuptools>=81 no longer ships.
    if "pkg_resources" not in sys.modules:
        try:
            import pkg_resources  # noqa: F401
        except ModuleNotFoundError:
            import packaging.version

            shim = types.ModuleType("pkg_resources")
            shim.packaging = packaging
            sys.modules["pkg_resources"] = shim

    import transformers.modeling_utils as modeling_utils
    import transformers.pytorch_utils as pytorch_utils

    if not hasattr(modeling_utils, "apply_chunking_to_forward"):
        modeling_utils.apply_chunking_to_forward = (
            pytorch_utils.apply_chunking_to_forward
        )
    if not hasattr(modeling_utils, "prune_linear_layer"):
        modeling_utils.prune_linear_layer = pytorch_utils.prune_linear_layer
    if not hasattr(modeling_utils, "find_pruneable_heads_and_indices"):

        def find_pruneable_heads_and_indices(
            heads, n_heads, head_size, already_pruned_heads
        ):
            mask = torch.ones(n_heads, head_size)
            heads = set(heads) - already_pruned_heads
            for head in heads:
                head = head - sum(1 if h < head else 0 for h in already_pruned_heads)
                mask[head] = 0
            mask = mask.view(-1).contiguous().eq(1)
            index = torch.arange(len(mask))[mask].long()
            return heads, index

        modeling_utils.find_pruneable_heads_and_indices = (
            find_pruneable_heads_and_indices
        )


@torch.inference_mode()
def calculate_image_reward(
    pred: list[Image.Image],
    prompts: list[str],
    device: str = "cuda",
) -> float:
    _patch_for_image_reward()
    import ImageReward as RM

    model = RM.load(name="ImageReward-v1.0", device=device)
    scores = [
        model.score(prompt, image.convert("RGB"))
        for image, prompt in zip(pred, prompts)
    ]
    return float(sum(scores) / len(scores))


@torch.inference_mode()
def calculate_fid(
    pred: list[Image.Image],
    target: list[Image.Image],
    device: str = "cuda",
    batch_size: int = 32,
) -> float:
    metric = FrechetInceptionDistance(normalize=True).to(device)
    for pred_batch, target_batch in _pair_batches(pred, target, batch_size, device):
        metric.update(target_batch, real=True)
        metric.update(pred_batch, real=False)
    score: torch.Tensor = metric.compute()
    return float(score.detach().cpu().item())


def compute_all_metrics(
    pred: list[Image.Image],
    target: list[Image.Image],
    prompts: list[str],
    device: str = "cuda",
    batch_size: int = 32,
):
    # 1. compute PSNR, SSIM, LPIPS scores.
    psnr = calculate_psnr(pred, target, device, batch_size)
    ssim = calculate_ssim(pred, target, device, batch_size)
    lpips = calculate_lpips(pred, target, device, batch_size)

    # 2. compute FID score.
    fid = calculate_fid(pred, target, device, batch_size)

    # 3. compute CLIP score.
    clip_score = calculate_clip_score(pred, prompts, device, batch_size)

    # 4. compute image reward score.
    image_reward_score = calculate_image_reward(pred, prompts, device)

    print("==================== METRICS ====================")
    print(f"[PSNR]: {psnr:.4f}")
    print(f"[SSIM]: {ssim:.4f}")
    print(f"[LPIPS]: {lpips:.4f}")
    print(f"[FID]: {fid:.4f}")
    print(f"[CLIP score]: {clip_score:.4f}")
    print(f"[ImageReward score]: {image_reward_score:.4f}")
    print("=================================================")

    return {
        "psnr": psnr,
        "ssim": ssim,
        "lpips": lpips,
        "fid": fid,
        "clip_score": clip_score,
        "image_reward_score": image_reward_score,
    }


def pair_samples(
    base: RunLog,
    taylorseer: RunLog,
    prompts: dict[int, str],
) -> list[PairedSample]:
    """Pair the samples of both runs by their global index in the data file.

    Samples present in only one run, whose image file is missing, or whose
    prompt cannot be recovered from the data file are reported and skipped.
    """
    indexes = sorted(base.samples.keys() & taylorseer.samples.keys())
    unpaired = base.samples.keys() ^ taylorseer.samples.keys()
    if unpaired:
        print(
            f"[metrics] skipping {len(unpaired)} unpaired sample(s): {sorted(unpaired)}"
        )

    paired: list[PairedSample] = []
    missing_images: list[int] = []
    prompt_mismatch: list[int] = []
    seed_mismatch: list[int] = []
    for index in indexes:
        base_record = base.samples[index]
        taylorseer_record = taylorseer.samples[index]

        missing = [
            str(record.image_path)
            for record in (base_record, taylorseer_record)
            if not record.image_path.is_file()
        ]
        if missing:
            missing_images.append(index)
            continue

        # The data file is the source of truth for the prompt; the logged prompt
        # is only used as a fallback (e.g. the data file has since changed).
        prompt = prompts.get(index, base_record.prompt)
        if prompt != base_record.prompt or prompt != taylorseer_record.prompt:
            prompt_mismatch.append(index)
        if base_record.seed != taylorseer_record.seed:
            seed_mismatch.append(index)

        paired.append(
            PairedSample(
                index=index,
                prompt=prompt,
                seed=base_record.seed,
                base=base_record,
                taylorseer=taylorseer_record,
            )
        )

    if missing_images:
        print(
            f"[metrics] skipping {len(missing_images)} sample(s) with missing image file(s): "
            f"{missing_images}"
        )
    if prompt_mismatch:
        print(
            f"[metrics] WARNING: {len(prompt_mismatch)} sample(s) whose prompt differs between "
            f"the data file and the run logs: {prompt_mismatch}"
        )
    if seed_mismatch:
        print(
            f"[metrics] WARNING: {len(seed_mismatch)} sample(s) generated with different seeds "
            f"in the two runs, pairwise metrics are not meaningful for them: {seed_mismatch}"
        )
    if not paired:
        raise RuntimeError(
            "no comparable sample pairs found; check that both run logs cover the same samples"
        )
    return paired


def summarize_latency(paired: list[PairedSample]) -> dict[str, float]:
    """Latency of both runs over the paired samples, plus the resulting speedup."""
    base = [pair.base.latency for pair in paired]
    taylorseer = [pair.taylorseer.latency for pair in paired]
    base_total, taylorseer_total = sum(base), sum(taylorseer)
    return {
        "num_samples": len(paired),
        "base_total_s": base_total,
        "taylorseer_total_s": taylorseer_total,
        "base_mean_s": base_total / len(base),
        "taylorseer_mean_s": taylorseer_total / len(taylorseer),
        "base_median_s": statistics.median(base),
        "taylorseer_median_s": statistics.median(taylorseer),
        "speedup": base_total / taylorseer_total
        if taylorseer_total > 0
        else float("inf"),
    }


def _run_summary(run: RunLog) -> dict:
    return {
        "run_name": run.run_name,
        "method": run.method,
        "log_files": [str(path) for path in run.paths],
        "num_logged_samples": len(run.samples),
        "config": run.config,
    }


def _resolve_report_path(args: MetricsArguments, taylorseer: RunLog) -> Path:
    if args.report_path:
        return Path(args.report_path)
    log_path = taylorseer.paths[0]
    return log_path.parent / f"{taylorseer.run_name}.metrics.json"


def main(args: MetricsArguments) -> None:
    base = load_run_log(args.base_log)
    taylorseer = load_run_log(args.taylorseer_log)
    if base.method != "base":
        print(f"[metrics] WARNING: --base_log is a '{base.method}' run, not 'base'")
    if taylorseer.method != "taylorseer":
        print(
            f"[metrics] WARNING: --taylorseer_log is a '{taylorseer.method}' run, not 'taylorseer'"
        )

    data_path = args.data_path or taylorseer.data_path or base.data_path
    if data_path is None:
        raise ValueError("--data_path is required: the run logs do not record one")
    samples = load_samples(data_path)
    prompts = {index: sample.prompt for index, sample in enumerate(samples)}

    paired = pair_samples(base, taylorseer, prompts)
    print(
        f"[metrics] comparing {len(paired)} sample pair(s): "
        f"'{taylorseer.run_name}' (pred) vs '{base.run_name}' (target), prompts from {data_path}"
    )

    target_images = [Image.open(pair.base.image_path) for pair in paired]
    pred_images = [Image.open(pair.taylorseer.image_path) for pair in paired]
    prompt_list = [pair.prompt for pair in paired]

    metrics = compute_all_metrics(
        pred_images,
        target_images,
        prompt_list,
        device=args.device,
        batch_size=args.batch_size,
    )
    latency = summarize_latency(paired)

    print("==================== LATENCY ====================")
    print(
        f"[base]: {latency['base_mean_s']:.2f}s/sample ({latency['base_total_s']:.2f}s total)"
    )
    print(
        f"[taylorseer]: {latency['taylorseer_mean_s']:.2f}s/sample "
        f"({latency['taylorseer_total_s']:.2f}s total)"
    )
    print(f"[speedup]: {latency['speedup']:.2f}x")
    print("=================================================")

    report = {
        "base": _run_summary(base),
        "taylorseer": _run_summary(taylorseer),
        "data_path": data_path,
        "num_paired_samples": len(paired),
        "metrics": metrics,
        "latency": latency,
        "samples": [
            {
                "index": pair.index,
                "prompt": pair.prompt,
                "seed": pair.seed,
                "base_latency": pair.base.latency,
                "taylorseer_latency": pair.taylorseer.latency,
                "base_image_path": str(pair.base.image_path),
                "taylorseer_image_path": str(pair.taylorseer.image_path),
            }
            for pair in paired
        ],
    }

    report_path = _resolve_report_path(args, taylorseer)
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(report, indent=2))
    print(f"[metrics] wrote {report_path}")


if __name__ == "__main__":
    parser = HfArgumentParser((MetricsArguments,))
    (metrics_args,) = parser.parse_args_into_dataclasses(return_remaining_strings=False)
    main(metrics_args)
